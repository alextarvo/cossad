class RunLogger:
    """Dual logger: writes to console and a log file."""

    def __init__(self, log_dir: str, dry_run: bool = False):
        self._dry_run = dry_run
        self._log_dir = log_dir
        self._log_path = os.path.join(log_dir, "run_log.txt")
        self._file = None

    def open(self):
        os.makedirs(self._log_dir, exist_ok=True)
        self._file = open(self._log_path, "w")

    def close(self):
        if self._file:
            self._file.close()
            self._file = None

    def __enter__(self):
        self.open()
        return self

    def __exit__(self, *args):
        self.close()

    def log(self, message: str):
        print(message)
        if self._file:
            self._file.write(message + "\n")
            self._file.flush()

    def log_header(self, config: "RunConfig"):
        mode = "[DRY-RUN] " if config.dry_run else ""
        self.log(f"{'=' * 60}")
        self.log(f"{mode}COSSAD Pipeline Runner")
        self.log(f"{'=' * 60}")
        self.log(f"Timestamp:       {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
        self.log(f"Stages:          {', '.join(config.stages)}")
        self.log(f"Weights run ID:  {config.weights_run_id}")
        self.log(f"Eval run ID:     {config.eval_run_id}")
        self.log(f"Splits:          {config.splits}")
        self.log(f"Epochs:          {config.epochs}")
        self.log(f"Attempts:        {config.attempts}")
        self.log(f"Train datasets:  {config.train_datasets}")
        self.log(f"Eval dataset:    {config.eval_dataset}")
        self.log(f"Data path:       {config.data_path}")
        self.log(f"Weights root:    {config.weights_root}")
        self.log(f"Predictions root:{config.predictions_root}")
        if config.extra_train_args:
            self.log(f"Extra train args:{' '.join(config.extra_train_args)}")
        if config.extra_eval_args:
            self.log(f"Extra eval args: {' '.join(config.extra_eval_args)}")
        self.log(f"{'=' * 60}")
        self.log("")

    def log_command(self, cmd: list, label: str):
        cmd_str = _format_command(cmd)
        self.log(f"  [{label}] {cmd_str}")

    def log_result(self, result: StageResult):
        label = result.stage_name
        if result.split is not None:
            label += f"@{result.split}"
        self.log(f"  [{label}] {result.status_str}")

    def log_summary(self, results: list):
        self.log("")
        self.log(f"{'─' * 60}")
        self.log("Summary:")
        self.log(f"{'─' * 60}")
        for r in results:
            label = r.stage_name
            if r.split is not None:
                label += f"@{r.split}"
            self.log(f"  {label:<24} {r.status_str}")

        failures = [r for r in results if not r.success]
        self.log(f"{'─' * 60}")
        if failures:
            self.log(f"RESULT: {len(failures)} stage(s) failed.")
        else:
            self.log("RESULT: All stages completed successfully.")
        self.log("")


def _format_command(cmd: list) -> str:
    """Format a command list as a copy-pasteable shell string.

    Groups flag-value pairs (e.g. --encoder riconv2) on the same line.
    Hydra overrides (key=value) each get their own line.
    """

    def _quote(arg: str) -> str:
        if " " in arg or "'" in arg or "[" in arg or "=" in arg:
            if "'" in arg:
                return f'"{arg}"'
            return f"'{arg}'"
        return arg

    # Group tokens into logical chunks: flag+value pairs, or standalone args
    chunks = []
    i = 0
    while i < len(cmd):
        token = cmd[i]
        if token.startswith("-") and not token.startswith("--config-path") \
                and i + 1 < len(cmd) and not cmd[i + 1].startswith("-") \
                and "=" not in cmd[i + 1]:
            # Flag followed by its value
            chunks.append(f"{_quote(token)} {_quote(cmd[i + 1])}")
            i += 2
        elif token.startswith("--") and i + 1 < len(cmd) and not cmd[i + 1].startswith("-") \
                and "=" not in token and "=" not in cmd[i + 1]:
            # Long flag followed by its value
            chunks.append(f"{_quote(token)} {_quote(cmd[i + 1])}")
            i += 2
        else:
            chunks.append(_quote(token))
            i += 1

    return " \\\n    ".join(chunks)


