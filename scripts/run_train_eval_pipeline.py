def resolve_config(args: argparse.Namespace) -> RunConfig:
    """Resolve CLI args + preset defaults into a RunConfig."""
    command = args.command

    # Determine stages
    if command in PRESETS:
        stages = ["train", "eval", "compare"]
        preset = PRESETS[command]
    elif command == "train":
        stages = ["train"]
        preset = PRESETS["full"]  # defaults for unspecified params
    elif command == "eval":
        stages = ["eval", "compare"]
        preset = PRESETS["full"]
    elif command == "compare":
        stages = ["compare"]
        preset = PRESETS["full"]
    else:
        raise ValueError(f"Unknown command: {command}")

    # Resolve parameters: CLI override > preset
    splits = _parse_splits(args.splits) if args.splits else preset["splits"]
    epochs = args.epochs if args.epochs is not None else preset["epochs"]
    attempts = args.attempts if args.attempts is not None else preset["attempts"]
    eval_dataset = args.eval_dataset or preset["eval_dataset"]
    train_datasets = (
        args.train_datasets.split(",") if args.train_datasets else preset["train_datasets"]
    )

    # Generate run IDs
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    weights_run_id = args.weights_run_id or f"Train_{timestamp}"
    eval_run_id = args.eval_run_id or f"Eval_{timestamp}"

    # For eval/compare-only, weights_run_id must be provided
    if command == "eval" and args.weights_run_id is None:
        print("WARNING: --weights-run-id not specified for eval. Using auto-generated ID.")
        print(f"  This means the runner will look for weights at: {args.weights_root}/{weights_run_id}/")
        print("  If re-evaluating existing weights, pass --weights-run-id explicitly.")

    extra_train_args = args.train_extra.split() if args.train_extra else []
    extra_eval_args = args.eval_extra.split() if args.eval_extra else []

    return RunConfig(
        stages=stages,
        splits=splits,
        epochs=epochs,
        attempts=attempts,
        train_datasets=train_datasets,
        eval_dataset=eval_dataset,
        weights_run_id=weights_run_id,
        eval_run_id=eval_run_id,
        data_path=args.data_path,
        weights_root=args.weights_root,
        predictions_root=args.predictions_root,
        dry_run=args.dry_run,
        extra_train_args=extra_train_args,
        extra_eval_args=extra_eval_args,
    )


def main():
    parser = build_parser()
    args = parser.parse_args()
    config = resolve_config(args)
    runner = PipelineRunner()
    exit_code = runner.run(config)
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
