TRAIN_MAX_ATTEMPTS = 2  # One initial attempt + one retry on failure


class TrainStage:
    """Builds and executes training commands for individual splits."""

    def build_command(self, split: int, config: RunConfig) -> list:
        datasets_str = (
            f"[{','.join(config.train_datasets)}]"
            if len(config.train_datasets) > 1
            else config.train_datasets[0]
        )
        patches_path = os.path.join(config.data_path, TRAIN_PATCHES_SUBDIR)
        hydra_run_dir = os.path.join(
            config.weights_root, config.weights_run_id, f"train_classes_{split}"
        )

        return [
            sys.executable,
            "contrastive_learner_v3.py",
            "--config-path",
            TRAIN_CONFIG_PATH,
            "--config-name",
            TRAIN_CONFIG_NAME,
            "-m",
            f"experiment.run_name={TRAIN_RUN_NAME_PREFIX}_{split}",
            f"experiment.run_id='{config.weights_run_id}'",
            f"experiment.tags={TRAIN_EXPERIMENT_TAGS}",
            f"data.split=train_classes_{split}",
            f"data.dataset={datasets_str}",
            f"data.patches_path={patches_path}",
            f"model.name={TRAIN_MODEL_NAME}",
            f"training.epochs={config.epochs}",
            f"hydra.run.dir={hydra_run_dir}",
            *config.extra_train_args,
        ]

    def is_complete(self, split: int, config: RunConfig) -> bool:
        return os.path.isfile(config.weights_path(split))

    def run(self, split: int, config: RunConfig, logger: RunLogger) -> StageResult:
        cmd = self.build_command(split, config)

        if self.is_complete(split, config):
            logger.log(f"  [train@{split}] SKIPPED — weights exist: {config.weights_path(split)}")
            logger.log_command(cmd, f"train@{split} (would have run)")
            return StageResult(
                stage_name="train", split=split, command=cmd,
                exit_code=None, skipped=True,
            )

        logger.log_command(cmd, f"train@{split}")

        if config.dry_run:
            return StageResult(
                stage_name="train", split=split, command=cmd,
                exit_code=None, dry_run=True,
            )

        exit_code = 1
        for attempt in range(1, TRAIN_MAX_ATTEMPTS + 1):
            attempt_label = f"train@{split} (attempt {attempt}/{TRAIN_MAX_ATTEMPTS})"
            if attempt > 1:
                logger.log(f"  [{attempt_label}] Retrying after previous failure")

            exit_code = self._run_one_attempt(cmd, split, config, logger, attempt_label)
            if exit_code == 0:
                break

        if exit_code != 0:
            logger.log(f"  [train@{split}] Giving up after {TRAIN_MAX_ATTEMPTS} attempts")

        return StageResult(
            stage_name="train", split=split, command=cmd, exit_code=exit_code,
        )

    def _run_one_attempt(
        self,
        cmd: list,
        split: int,
        config: RunConfig,
        logger: RunLogger,
        attempt_label: str,
    ) -> int:
        """Run training once. Returns 0 on success, non-zero on failure.

        Failure is declared if either the subprocess exits non-zero OR
        exits zero but the .pth sentinel is missing (Hydra multirun can
        swallow exceptions, so the sentinel is the load-bearing signal).
        """
        result = subprocess.run(cmd)
        exit_code = result.returncode
        pth_exists = os.path.isfile(config.weights_path(split))

        if exit_code == 0 and pth_exists:
            logger.log(f"  [{attempt_label}] Training completed — sentinel confirmed: {config.weights_path(split)}")
            return 0

        if exit_code == 0 and not pth_exists:
            logger.log(f"  [{attempt_label}] WARNING: exit code 0 but sentinel NOT found: {config.weights_path(split)}")
            return 1

        logger.log(f"  [{attempt_label}] FAILED with exit code {exit_code}")
        return exit_code


class EvalStage:
    """Builds and executes eval commands for individual splits."""

    def build_command(self, split: int, config: RunConfig) -> list:
        encoder_path = config.weights_path(split)
        dataset_flags = DATASET_EVAL_FLAGS.get(config.eval_dataset, [])

        cmd = [
            sys.executable,
            "pipeline_reg_based.py",
            "--cossad_data_path", config.data_path,
            "--object_classes", f"{config.eval_dataset}_test_classes_{split}",
            "--contrastive_encoder_path", encoder_path,
            "--output_results_path", os.path.join(config.predictions_root, config.eval_run_id),
            "--encoder", EVAL_ENCODER,
            "--patch_radius", str(EVAL_PATCH_RADIUS),
            *dataset_flags,
            *config.extra_eval_args,
        ]
        return cmd

    def run(self, split: int, config: RunConfig, logger: RunLogger) -> StageResult:
        # Check dependency: weights must exist
        encoder_path = config.weights_path(split)
        if not config.dry_run and not os.path.isfile(encoder_path):
            logger.log(f"  [eval@{split}] ERROR — weights not found: {encoder_path}")
            logger.log(f"  Cannot run eval without trained weights for split {split}.")
            return StageResult(
                stage_name="eval", split=split,
                command=self.build_command(split, config),
                exit_code=1,
            )

        cmd = self.build_command(split, config)
        logger.log_command(cmd, f"eval@{split}")

        if config.dry_run:
            if not os.path.isfile(encoder_path):
                logger.log(f"  [eval@{split}] NOTE: weights not yet present: {encoder_path}")
            return StageResult(
                stage_name="eval", split=split, command=cmd,
                exit_code=None, dry_run=True,
            )

        result = subprocess.run(cmd)
        exit_code = result.returncode

        if exit_code != 0:
            logger.log(f"  [eval@{split}] FAILED with exit code {exit_code}")
        else:
            logger.log(f"  [eval@{split}] Completed successfully")

        return StageResult(
            stage_name="eval", split=split, command=cmd, exit_code=exit_code,
        )


class CompareStage:
    """Builds and executes the comparison against baseline."""

    def build_command(self, config: RunConfig) -> list:
        return [
            sys.executable,
            "scripts/compare_models.py",
            "--ref", config.baseline_stats_path(),
            "--test", config.eval_stats_path(),
            "--output", config.comparison_output_path(),
            "--strict",
        ]

    def run(self, config: RunConfig, logger: RunLogger) -> StageResult:
        cmd = self.build_command(config)
        logger.log_command(cmd, "compare")

        if config.dry_run:
            return StageResult(
                stage_name="compare", split=None, command=cmd,
                exit_code=None, dry_run=True,
            )

        result = subprocess.run(cmd)
        exit_code = result.returncode

        if exit_code != 0:
            logger.log("  [compare] Test mean < baseline mean (regression detected)")
        else:
            logger.log("  [compare] Test meets or exceeds baseline")

        return StageResult(
            stage_name="compare", split=None, command=cmd, exit_code=exit_code,
        )


