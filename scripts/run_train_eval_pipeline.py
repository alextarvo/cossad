class PipelineRunner:
    """Orchestrates the train → eval → compare pipeline."""

    def __init__(self):
        self._train = TrainStage()
        self._eval = EvalStage()
        self._compare = CompareStage()

    def run(self, config: RunConfig) -> int:
        """Run the pipeline. Returns 0 on success, 1 on failure."""
        with RunLogger(config.log_dir(), config.dry_run) as logger:
            logger.log_header(config)
            results = []

            if "train" in config.stages:
                logger.log("── Train ──")
                train_results = self._run_train(config, logger)
                results.extend(train_results)

                train_failures = [r for r in train_results if not r.success]
                if train_failures and not config.dry_run:
                    logger.log(f"\n{len(train_failures)} training split(s) failed. Aborting.")
                    logger.log_summary(results)
                    return 1
                logger.log("")

            if "eval" in config.stages:
                logger.log("── Eval ──")
                eval_results = self._run_eval(config, logger)
                results.extend(eval_results)

                eval_failures = [r for r in eval_results if not r.success]
                if eval_failures and not config.dry_run:
                    logger.log(f"\n{len(eval_failures)} eval split(s) failed. Aborting.")
                    logger.log_summary(results)
                    return 1
                logger.log("")

            if "compare" in config.stages:
                logger.log("── Compare ──")
                compare_result = self._compare.run(config, logger)
                results.append(compare_result)
                # compare non-zero is informational, not a pipeline failure
                logger.log("")

            logger.log_summary(results)
            logger.log(f"Log written to: {os.path.join(config.log_dir(), 'run_log.txt')}")

            hard_failures = [
                r for r in results
                if not r.success and r.stage_name != "compare"
            ]
            return 1 if hard_failures else 0

    def _run_train(self, config: RunConfig, logger: RunLogger) -> list:
        results = []
        for split in config.splits:
            result = self._train.run(split, config, logger)
            results.append(result)
            logger.log_result(result)
            if not result.success and not config.dry_run:
                break  # Stop on first failure
        return results

    def _run_eval(self, config: RunConfig, logger: RunLogger) -> list:
        results = []
        for split in config.splits:
            for attempt in range(1, config.attempts + 1):
                if config.attempts > 1:
                    logger.log(f"  Attempt {attempt}/{config.attempts} for split {split}")
                result = self._eval.run(split, config, logger)
                results.append(result)
                logger.log_result(result)
                if not result.success and not config.dry_run:
                    break  # Stop on first failure
            else:
                continue
            break  # Propagate break from inner loop
        return results


