@dataclass
class RunConfig:
    """Resolved parameters for a pipeline run."""

    stages: list  # subset of ["train", "eval", "compare"]
    splits: list
    epochs: int
    attempts: int
    train_datasets: list
    eval_dataset: str
    weights_run_id: str
    eval_run_id: str
    data_path: str
    weights_root: str
    predictions_root: str
    dry_run: bool
    extra_train_args: list = field(default_factory=list)
    extra_eval_args: list = field(default_factory=list)

    @property
    def sentinel_filename(self) -> str:
        return f"best_{TRAIN_MODEL_NAME}.pth"

    def weights_path(self, split: int) -> str:
        return os.path.join(
            self.weights_root,
            self.weights_run_id,
            f"train_classes_{split}",
            self.sentinel_filename,
        )

    def eval_stats_path(self) -> str:
        return os.path.join(
            self.predictions_root, self.eval_run_id, "stats", "all.csv"
        )

    def baseline_stats_path(self) -> str:
        return os.path.join(self.predictions_root, BASELINE_STATS_SUBPATH)

    def comparison_output_path(self) -> str:
        return os.path.join(
            self.predictions_root, self.eval_run_id, "comparison_results.csv"
        )

    def log_dir(self) -> str:
        return os.path.join(self.predictions_root, self.eval_run_id)


@dataclass
class StageResult:
    """Outcome of a single stage execution."""

    stage_name: str
    split: Optional[int]
    command: list
    exit_code: Optional[int]  # None if skipped or dry-run
    skipped: bool = False
    dry_run: bool = False

    @property
    def success(self) -> bool:
        if self.skipped or self.dry_run:
            return True
        return self.exit_code == 0

    @property
    def status_str(self) -> str:
        if self.skipped:
            return "SKIPPED"
        if self.dry_run:
            return "DRY-RUN"
        if self.exit_code == 0:
            return "OK"
        return f"FAILED (exit {self.exit_code})"


