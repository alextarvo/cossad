def _generate_run_id(prefix: str) -> str:
    return f"{prefix}_{datetime.now().strftime('%Y%m%d_%H%M%S')}"


def _parse_splits(splits_str: str) -> list:
    """Parse '2,3,4' or '1-12' into a list of ints."""
    parts = splits_str.split(",")
    result = []
    for part in parts:
        part = part.strip()
        if "-" in part:
            lo, hi = part.split("-", 1)
            result.extend(range(int(lo), int(hi) + 1))
        else:
            result.append(int(part))
    return result


